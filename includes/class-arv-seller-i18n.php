	/**
	 * Active language key (e.g. 'fa', 'en', 'ar', 'tr', 'zh', 'ru').
	 *
	 * @var string
	 */
	protected static $active_lang = 'fa';

	/**
	 * Initialize i18n hooks and language resolution.
	 *
	 * @since    1.0.0
	 */
	public function init() {
		self::resolve_active_language();

		// Hook textdomain loader
		add_action( 'plugins_loaded', array( $this, 'load_plugin_textdomain' ) );

		// Dynamic gettext filter for runtime translations
		add_filter( 'gettext', array( $this, 'filter_translations' ), 20, 3 );
		add_filter( 'gettext_with_context', array( $this, 'filter_translations_with_context' ), 20, 4 );
	}

	/**
	 * Determine the active language from WordPress locale (primary source of truth),
	 * with optional explicit cookie/query parameter override.
	 */
	public static function resolve_active_language() {
		// 1. Explicit Cookie Override
		if ( isset( $_COOKIE['arvan_lang'] ) && isset( self::LANGUAGES[ sanitize_key( $_COOKIE['arvan_lang'] ) ] ) ) {
			self::$active_lang = sanitize_key( $_COOKIE['arvan_lang'] );
			return self::$active_lang;
		}

		// 2. Synchronize directly with WordPress Site Locale
		$wp_locale = function_exists( 'determine_locale' ) ? determine_locale() : ( function_exists( 'get_user_locale' ) ? get_user_locale() : ( function_exists( 'get_locale' ) ? get_locale() : 'fa_IR' ) );

		if ( empty( $wp_locale ) ) {
			$wp_locale = function_exists( 'get_locale' ) ? get_locale() : 'fa_IR';
		}

		$wp_locale = strtolower( str_replace( '-', '_', $wp_locale ) );

		if ( 0 === strpos( $wp_locale, 'fa' ) || 0 === strpos( $wp_locale, 'pes' ) ) {
			self::$active_lang = 'fa';
		} elseif ( 0 === strpos( $wp_locale, 'ar' ) ) {
			self::$active_lang = 'ar';
		} elseif ( 0 === strpos( $wp_locale, 'tr' ) ) {
			self::$active_lang = 'tr';
		} elseif ( 0 === strpos( $wp_locale, 'zh' ) ) {
			self::$active_lang = 'zh';
		} elseif ( 0 === strpos( $wp_locale, 'ru' ) ) {
			self::$active_lang = 'ru';
		} elseif ( 0 === strpos( $wp_locale, 'en' ) ) {
			self::$active_lang = 'en';
		} else {
			self::$active_lang = ( function_exists( 'is_rtl' ) && is_rtl() ) ? 'fa' : 'en';
		}

		return self::$active_lang;
	}

	/**
	 * Get active language identifier ('fa', 'en', 'ar', 'tr', 'zh', 'ru').
	 *
	 * @return string
	 */
	public static function get_active_language() {
		if ( empty( self::$active_lang ) ) {
			self::resolve_active_language();
		}
		return self::$active_lang;
	}

	/**
	 * Get layout direction ('rtl' or 'ltr') for the active language.
	 *
	 * @return string
	 */
	public static function get_direction() {
		$lang = self::get_active_language();
		return isset( self::LANGUAGES[ $lang ]['direction'] ) ? self::LANGUAGES[ $lang ]['direction'] : 'rtl';
	}

	/**
	 * Alias for get_direction()
	 *
	 * @return string
	 */
	public static function get_active_direction() {
		return self::get_direction();
	}

	/**
	 * Get all supported languages configuration.
	 *
	 * @return array
	 */
	public static function get_supported_languages() {
		return self::LANGUAGES;
	}

	/**
	 * Get dictionary for a given language.
	 *
	 * @param string $lang Language short code.
	 * @return array
	 */
	public static function get_dictionary( $lang = 'fa' ) {
		return isset( self::DICTIONARIES[ $lang ] ) ? self::DICTIONARIES[ $lang ] : self::DICTIONARIES['fa'];
	}

	/**
	 * Translate a string using the active dictionary.
	 *
	 * @param string $text Text string in English or Persian.
	 * @param string $lang Optional target language.
	 * @return string
	 */
	public static function translate( $text, $lang = null ) {
		if ( empty( $lang ) ) {
			$lang = self::get_active_language();
		}

		$dict = self::get_dictionary( $lang );
		if ( isset( $dict[ $text ] ) ) {
			return $dict[ $text ];
		}

		return $text;
	}

	/**
	 * Load plugin textdomain for WordPress gettext system.
	 *
	 * @since    1.0.0
	 */
	public function load_plugin_textdomain() {
		load_plugin_textdomain(
			'arv-seller',
			false,
			dirname( dirname( plugin_basename( __FILE__ ) ) ) . '/languages/'
		);
	}

	/**
	 * Filter gettext calls for arv-seller domain to support runtime switching.
	 *
	 * @param string $translated_text
	 * @param string $text
	 * @param string $domain
	 * @return string
	 */
	public function filter_translations( $translated_text, $text, $domain ) {
		if ( 'arv-seller' !== $domain ) {
			return $translated_text;
		}

		$active_lang = self::get_active_language();
		$dict        = self::get_dictionary( $active_lang );

		if ( isset( $dict[ $text ] ) && '' !== $dict[ $text ] ) {
			return $dict[ $text ];
		}

		return $translated_text;
	}

	/**
	 * Filter gettext_with_context calls for arv-seller domain.
	 *
	 * @param string $translated_text
	 * @param string $text
	 * @param string $context
	 * @param string $domain
	 * @return string
	 */
	public function filter_translations_with_context( $translated_text, $text, $context, $domain ) {
		if ( 'arv-seller' !== $domain ) {
			return $translated_text;
		}

		return $this->filter_translations( $translated_text, $text, $domain );
	}
