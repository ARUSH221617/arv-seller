	/**
	 * Load the plugin text domain for translation.
	 *
	 * @since    1.0.0
	 */
	public function load_plugin_textdomain() {
		load_plugin_textdomain(
			'arv-seller',
			false,
			dirname( dirname( plugin_basename( __FILE__ ) ) ) . '/languages/'
		);
	}

	/**
	 * Filter translation strings dynamically for domain 'arv-seller'.
	 *
	 * @param string $translation Translated text.
	 * @param string $text        Original text.
	 * @param string $domain      Text domain.
	 * @return string
	 */
	public function filter_translations( $translation, $text, $domain ) {
		if ( 'arv-seller' !== $domain ) {
			return $translation;
		}

		$lang = self::get_active_language();
		if ( 'en' === $lang ) {
			return $text; // English is base string
		}

		$dict = self::get_dictionary( $lang );
		return isset( $dict[ $text ] ) ? $dict[ $text ] : $translation;
	}

	/**
	 * Filter translation with context.
	 */
	public function filter_translations_with_context( $translation, $text, $context, $domain ) {
		return $this->filter_translations( $translation, $text, $domain );
	}

